#!/usr/bin/env python3
"""Differential core syntax cases within the documented JSON-context subset."""
import importlib.metadata
import json
from pathlib import Path
from jinja2 import Environment
assert importlib.metadata.version('Jinja2') == '3.1.6'
assert importlib.metadata.version('MarkupSafe') == '3.0.3'
ROOT=Path(__file__).resolve().parents[1]
cases=[]
def case(name,source,context=None,error=False):
    try:
        expected=Environment(autoescape=True).from_string(source).render(context or {})
    except Exception as e:
        if not error: raise
        expected=None
        kind=type(e).__name__
    else:
        if error: raise AssertionError(name+' did not fail')
        kind=None
    cases.append(dict(name=name,source=source,context=context or {},expected=expected,error=kind))
for i,source in enumerate([
    'Plain 😀é終 text', '', '{{ "é😀終" }}', '{{ "}}" }}', '{{ "%}" }}',
    '{{ "and" }}:{{ "or" }}:{{ "not" }}', '{{ "a\\nb\\t\\\"" }}',
    'A{# {{ignored}} {% ignored %} #}B', 'A \n{{- "B" -}} \n C',
    'A \n{#- ignored -#} \n B', 'A \n{% if true -%}\n B {%- endif %} C',
    '{% if false %}A{% elif true %}B{% else %}C{% endif %}',
    '{% if true %}{% if false %}A{% else %}B{% endif %}{% endif %}',
    '{% set x=2 %}{% if true %}{% set x=x+1 %}{% endif %}{{x}}',
    '{{ true }}:{{ false }}:{{ none }}', '{{ 1+2*3 }}:{{ (1+2)*3 }}',
    '{{ -7//3 }}:{{ -7%3 }}:{{ 7%-3 }}', '{{ 3/2 }}:{{ 4/2 }}',
    '{{ not 1>2 }}:{{ not true and false }}:{{ not (true and false) }}',
    '{{ false and (1/0) }}:{{ true or (1/0) }}',
    '{{ 1<2<3 }}:{{ 3<2<(1/0) }}', '{{ 1 != 2 }}:{{ 1 <= 1 }}:{{ 2 >= 1 }}',
    '{{ "A" < "B" }}:{{ "x" ~ 1 ~ true }}',
    '{{ missing }}:{{ missing or "fallback" }}',
]): case('syntax '+str(i),source)
for i,source in enumerate([
    '{{ user.name }}/{{user["name"]}}', '{{items[-1]}}/{{items[99]}}',
    '{{text[1]}}/{{text[-1]}}', '{{ 2 in items }}:{{ 7 not in items }}',
    '{{ "name" in user }}:{{ "da" in user.name }}',
    '{% for x in items %}{{loop.index}}={{x}};{% else %}empty{% endfor %}',
    '{% for x in empty %}X{% else %}empty{% endfor %}',
    '{% for x in missing %}X{% else %}missing{% endfor %}',
    '{% for x in text %}{{x}}{% endfor %}',
    '{% for x in user %}{{x}};{% endfor %}',
    '{% set x=9 %}{% for x in items %}{{x}}{% set x=7 %}{% endfor %}{{x}}',
    '{% set y=9 %}{% for x in items %}{{y}}{% set y=7 %}{% endfor %}{{y}}',
    '{% for x in items %}{% for y in items %}{{loop.index}}{% endfor %}{{loop.index}}{% endfor %}',
    '{% for x in items %}{{loop.first}}/{{loop.last}}/{{loop.length}}/{{loop.revindex0}};{% endfor %}',
    '{% set x=1 %}{% for y in empty %}X{% else %}{% set x=2 %}{{x}}{% endfor %}{{x}}',
]): case('context '+str(i), source,dict(user={'name':'Ada','age':25},items=[1,2,3],empty=[],text='é😀終'))
for i,source in enumerate(['{{','{%','{{ "broken }}','{{ 1+ }}','{% if true %}',
    '{% if false %}{{1+}}{% endif %}','{% unknown %}','{% else %}',
    '{% for x in values %}{% endif %}','{{value[1}}','{{value.}}','{{(1+2}}',
    '{{1/0}}','{{1%0}}','{{1 in 2}}','{% for x in 1 %}x{% endfor %}',
]): case('invalid '+str(i),source,error=True)
q=lambda s:json.dumps(s,ensure_ascii=False)
header='''# Generated by tools/generate-core-fixtures.py.
import templates

def context(str text) -> dict[str, JsonValue]:
    match json.loads(text):
        case JsonValue.Object(fields):
            return fields
        case _:
            return {}

def check(str name, str source, str data, str expected):
    auto actual = templates.render(source, context(data))
    if actual != expected:
        raise name + ": expected [" + expected + "] got [" + actual + "]"

def bad(str name, str source, str data):
    auto caught = False
    try:
        auto output = templates.render(source, context(data))
    except Exception as e:
        assert "TemplateError at character " in str(e)
        caught = True
    if not caught:
        raise name + ": expected template error"

def main():
'''
lines=[header]
for c in cases:
    args=', '.join(map(q,[c['name'],c['source'],json.dumps(c['context'],ensure_ascii=False)]))
    if c['error']:lines.append(f'    bad({args})\n')
    else:lines.append(f'    check({args}, {q(c["expected"])})\n')
lines.append(f'    print("Jinja core fixtures: {len(cases)} PASS")\n')
(ROOT/'tests/core_fixtures_test.zap').write_text(''.join(lines))
(ROOT/'tests/fixtures/core.json').write_text(json.dumps(dict(jinja='3.1.6',markupsafe='3.0.3',cases=cases),indent=2,ensure_ascii=False)+'\n')
print(f'Generated {len(cases)} core fixtures')
